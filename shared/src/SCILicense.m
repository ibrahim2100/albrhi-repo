#pragma mark - The device

/// A value from libMobileGestalt, or nil.
///
/// `dlopen`/`dlsym` rather than a link: MobileGestalt is private, its presence is not something
/// to assume, and a missing symbol has to be an answer rather than a launch failure. Every
/// caller below treats nil as "use something else", which is why a device that refuses to
/// answer still gets a fingerprint.
static NSString *SCIGestaltString(NSString *question) {
    static void *handle = NULL;
    static CFStringRef (*copyAnswer)(CFStringRef) = NULL;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        handle = dlopen("/usr/lib/libMobileGestalt.dylib", RTLD_LAZY);
        if (handle) copyAnswer = (CFStringRef (*)(CFStringRef))dlsym(handle, "MGCopyAnswer");
    });

    if (!copyAnswer) return nil;

    CFStringRef answer = copyAnswer((__bridge CFStringRef)question);
    if (!answer) return nil;

    NSString *value = (__bridge_transfer NSString *)answer;
    return [value isKindOfClass:[NSString class]] && value.length ? value : nil;
}

/// The hardware model, from the kernel. Present on every device and unique to none.
static NSString *SCIHardwareModel(void) {
    char buffer[64] = {0};
    size_t size = sizeof(buffer) - 1;
    if (sysctlbyname("hw.machine", buffer, &size, NULL, 0) != 0) return @"?";
    return [NSString stringWithUTF8String:buffer] ?: @"?";
}

static NSString *const kSCIDevicePref = @"licence_device";
static NSString *const kSCIServerPref = @"licence_server";

/// Eight random bytes as sixteen hex characters.
///
/// Random rather than derived, which is the whole correction. A derived id has to be derivable in
/// every process that needs it, and the value this used to derive from -- MobileGestalt's serial
/// number -- is readable in Settings and not in a sandboxed app. A random id has no such problem
/// and identifies nothing about the phone or its owner.
static NSString *SCIFreshDeviceIdentity(void) {
    uint8_t bytes[8];
    if (SecRandomCopyBytes(kSecRandomDefault, sizeof(bytes), bytes) != errSecSuccess) {
        // Never a silent weaker fallback. An identity that might be predictable is worse than no
        // identity, because a key would be issued against it and trusted.
        return nil;
    }

    NSMutableString *hex = [NSMutableString string];
    for (int i = 0; i < 8; i++) [hex appendFormat:@"%02x", bytes[i]];
    return hex;
}

/// The legacy shape, kept only so a process with no provisioned identity still answers something.
///
/// Marked weak wherever it surfaces. It is deliberately *not* used for anything but saying "the
/// panel has not been opened yet": issuing a key against it is what caused the fault this whole
/// function was rewritten for.
static NSString *SCIProvisionalIdentity(void) {
    NSString *material = [NSString stringWithFormat:@"%@|%@|provisional",
                          kSCILicenseSalt, SCIHardwareModel()];

    NSData *bytes = [material dataUsingEncoding:NSUTF8StringEncoding];
    unsigned char digest[CC_SHA256_DIGEST_LENGTH];
    CC_SHA256(bytes.bytes, (CC_LONG)bytes.length, digest);

    NSMutableString *hex = [NSMutableString string];
    for (int i = 0; i < 8; i++) [hex appendFormat:@"%02x", digest[i]];
    return hex;
}

/// The identity this process can actually read back.
///
/// **`com.albrhi.panel` is the right home and it is not always reachable.** On a jailbroken phone
/// every tweak reads that domain through `SCIPanelGate`'s file fallback, so one identity serves
/// the whole install and one licence covers everything — which is the behaviour to keep. A tweak
/// injected into an IPA on a phone with no jailbreak has no such file and no such domain: writing
/// there is answered by cfprefsd putting the value in this app's own container, and the next app
/// reads nothing at all.
///
/// So the write goes to the panel's domain when this process can read the panel's domain back,
/// and to the app's own otherwise. The test is a *read after write*, because a sandboxed write is
/// redirected rather than refused — the Watch tweak spent a release believing a write that had
/// gone somewhere else entirely.
static NSString *const kSCIOwnDomainDevicePref = @"albrhi_device_local";

static BOOL SCIWriteIdentity(NSString *value, NSString *domain) {
    CFPreferencesSetAppValue((__bridge CFStringRef)kSCIDevicePref,
                             (__bridge CFStringRef)value, (__bridge CFStringRef)domain);
    CFPreferencesAppSynchronize((__bridge CFStringRef)domain);

    NSString *back = SCIPanelReadString(kSCIDevicePref, nil);
    return [back isEqualToString:value];
}

void SCILicenseProvisionDevice(void) {
    NSString *stored = SCIPanelReadString(kSCIDevicePref, nil);
    if (stored.length == 16) return;

    // The app's own, from an earlier launch of a self-contained build.
    NSString *own = [[NSUserDefaults standardUserDefaults] stringForKey:kSCIOwnDomainDevicePref];
    if (own.length == 16) return;

    NSString *fresh = SCIFreshDeviceIdentity();
    if (!fresh) return;

    //
    // **Where a panel exists, the panel provisions and nothing else does.**
    //
    // One activation in Settings › Albrhi is meant to license every tweak on the phone, and that
    // only holds while they all share one identity. A tweak that provisions its own would take a
    // second identity that the panel cannot see -- and it would *seem* to work, because a
    // sandboxed write to the panel's domain is redirected into this app's container and reads
    // back perfectly from there.
    //
    // So on a device with a panel this waits. The screen says to activate from the panel, which
    // is the true answer rather than a provisional id nobody can issue a licence against.
    //
    if (SCIPanelIsInstalled()) {
        SCIWriteIdentity(fresh, @"com.albrhi.panel");
        return;
    }

    if (SCIWriteIdentity(fresh, @"com.albrhi.panel")) return;

    // Not readable there, so this process is on its own: its own defaults, which it can always
    // read, and a licence issued to this app rather than to the phone. That is the trade a
    // sideloaded install makes, and it is why licences carry a scope.
    [[NSUserDefaults standardUserDefaults] setObject:fresh forKey:kSCIOwnDomainDevicePref];
}

NSString *SCILicenseFingerprint(void) {
    // Not memoised across the process's life, unlike everything else here.
    //
    // The panel provisions the identity while this same process is running, so a cached "there
    // isn't one" would outlive the moment one appeared -- and the page would go on showing a
    // provisional id right after writing a real one. The read is a preference lookup; it is
    // cheap enough to do honestly.
    NSString *stored = SCIPanelReadString(kSCIDevicePref, nil);
    if (stored.length == 16) {
        sciFingerprintWeak = NO;
        return stored.lowercaseString;
    }

    // The app's own, written when the panel's domain could not be read back. Second, never
    // first: where the panel is reachable its identity is the one that makes a single licence
    // cover the whole phone.
    NSString *own = [[NSUserDefaults standardUserDefaults] stringForKey:kSCIOwnDomainDevicePref];
    if (own.length == 16) {
        sciFingerprintWeak = NO;
        return own.lowercaseString;
    }

    sciFingerprintWeak = YES;
    return SCIProvisionalIdentity();
}

BOOL SCILicenseFingerprintIsWeak(void) {
    SCILicenseFingerprint();       // sets the flag as a side effect of answering
    return sciFingerprintWeak;
}


#pragma mark - The key

static NSData *SCIBase64URLDecode(NSString *text) {
    if (!text.length) return nil;

    NSMutableString *padded = [text mutableCopy];
    [padded replaceOccurrencesOfString:@"-" withString:@"+"
                               options:0 range:NSMakeRange(0, padded.length)];
    [padded replaceOccurrencesOfString:@"_" withString:@"/"
                               options:0 range:NSMakeRange(0, padded.length)];
    while (padded.length % 4) [padded appendString:@"="];

    return [[NSData alloc] initWithBase64EncodedString:padded options:0];
}

/// The signature check itself.
///
/// `kSecKeyAlgorithmECDSASignatureMessageX962SHA256` hashes the message and verifies a DER
/// signature, which is exactly what `openssl dgst -sha256 -sign` produces — the two sides were
/// chosen together rather than made to meet afterwards.
static BOOL SCIVerifySignature(NSData *signedBytes, NSData *signature) {
    if (!signedBytes.length || !signature.length) return NO;

    NSData *point = [NSData dataWithBytes:kSCILicensePublicKey length:sizeof(kSCILicensePublicKey)];
    NSDictionary *attributes = @{
        (__bridge id)kSecAttrKeyType:  (__bridge id)kSecAttrKeyTypeECSECPrimeRandom,
        (__bridge id)kSecAttrKeyClass: (__bridge id)kSecAttrKeyClassPublic,
        (__bridge id)kSecAttrKeySizeInBits: @256,
    };

    CFErrorRef error = NULL;
    SecKeyRef key = SecKeyCreateWithData((__bridge CFDataRef)point,
                                         (__bridge CFDictionaryRef)attributes, &error);
    if (!key) {
        if (error) CFRelease(error);
        return NO;
    }

    BOOL ok = SecKeyVerifySignature(key,
                                    kSecKeyAlgorithmECDSASignatureMessageX962SHA256,
                                    (__bridge CFDataRef)signedBytes,
                                    (__bridge CFDataRef)signature,
                                    &error);
    CFRelease(key);
    if (error) CFRelease(error);
    return ok;
}

/// Parses and checks a key, without touching storage.
///
/// Order matters and is deliberate: **signature first, contents afterwards.** Reading a device
/// id or an expiry date out of a payload nobody has authenticated is reading whatever the person
/// holding the file decided to put there.
static SCILicenseState SCIEvaluateKey(NSString *key, NSDictionary **outPayload) {
    if (outPayload) *outPayload = nil;
    if (!key.length) return SCILicenseStateNone;

    NSArray<NSString *> *parts = [[key stringByTrimmingCharactersInSet:
        [NSCharacterSet whitespaceAndNewlineCharacterSet]] componentsSeparatedByString:@"."];

    if (parts.count != 3 || ![parts[0] isEqualToString:@"ALB1"]) return SCILicenseStateMalformed;

    NSString *signingInput = [NSString stringWithFormat:@"%@.%@", parts[0], parts[1]];
    NSData *signature = SCIBase64URLDecode(parts[2]);

    if (!SCIVerifySignature([signingInput dataUsingEncoding:NSUTF8StringEncoding], signature)) {
        return SCILicenseStateMalformed;
    }

    NSData *body = SCIBase64URLDecode(parts[1]);
    NSDictionary *payload = body ? [NSJSONSerialization JSONObjectWithData:body options:0 error:NULL] : nil;
    if (![payload isKindOfClass:[NSDictionary class]]) return SCILicenseStateMalformed;

    if (outPayload) *outPayload = payload;

    NSString *device = payload[@"dev"];
    if (![device isKindOfClass:[NSString class]] ||
        ![device.lowercaseString isEqualToString:SCILicenseFingerprint()]) {
        return SCILicenseStateWrongDevice;
    }

    NSNumber *expiry = payload[@"exp"];
    if (![expiry isKindOfClass:[NSNumber class]]) return SCILicenseStateMalformed;
    if (expiry.doubleValue <= [NSDate date].timeIntervalSince1970) return SCILicenseStateExpired;

    return SCILicenseStateValid;
}


#pragma mark - Storage and state

NSString *SCILicenseStoredKey(void) {
    NSString *key = SCIPanelReadString(kSCILicenseKeyPref, nil);
    return key.length ? key : nil;
}

BOOL SCILicenseIsEnforced(void) {
    //
    // **Always. There is no switch, and there was one for exactly one release.**
    //
    // It shipped as a preference so the layer could be introduced before it was enforced, which
    // was the right order — but a preference lives in the panel, the panel ships to everybody, and
    // a licence gate with a user-visible off switch is not a gate. Anyone could turn it off and
    // use the whole suite. That is not a hole to narrow; it is the wrong shape.
    //
    // **Nobody is locked out by this.** The panel is a Settings bundle and never asks the gate, so
    // the screen that enters a licence is always reachable — and a key issued by
    // `tools/licence.py` verifies with no server and no network at all. The way back in is
    // entering a licence, which is the only way back in that is not also a way around.
    //
    return YES;
}

/// The last time the server confirmed the key, and the ids it has revoked.
///
/// In NSUserDefaults for this process rather than in the panel's plist: a sandboxed app cannot
/// write the panel's domain -- that is a lesson this repository already paid for with the Watch
/// tweak -- and this is a cache, not a setting. Each app keeping its own copy costs one request
/// per app per six hours and needs no cross-sandbox write at all.
static NSString *const kSCILastCheckDefault = @"albrhi_licence_last_check";
static NSString *const kSCIRevokedDefault   = @"albrhi_licence_revoked";

static BOOL SCIKeyIsRevoked(NSDictionary *payload) {
    NSString *identifier = payload[@"id"];
    if (![identifier isKindOfClass:[NSString class]] || !identifier.length) return NO;

    NSArray *revoked = [[NSUserDefaults standardUserDefaults] arrayForKey:kSCIRevokedDefault];
    return [revoked isKindOfClass:[NSArray class]] && [revoked containsObject:identifier];
}

SCILicenseState SCILicenseCurrentState(void) {
    NSDictionary *payload = nil;
    SCILicenseState state = SCIEvaluateKey(SCILicenseStoredKey(), &payload);

    // Two ways to be licensed, and the better answer wins.
    //
    // A device can hold a key *and* have redeemed a code -- somebody who bought a code and later
    // got a key issued directly, most obviously. Refusing on the strength of whichever happens to
    // be worse would take a working licence away from a paying user over a leftover.
    if (state != SCILicenseStateValid) {
        SCILicenseState fromCode = SCICodeState();
        if (fromCode == SCILicenseStateValid) return SCILicenseStateValid;
        if (state == SCILicenseStateNone && fromCode != SCILicenseStateNone) return fromCode;
        return state;
    }

    if (SCIKeyIsRevoked(payload)) return SCILicenseStateRevoked;

    // Grace. The key is signed and in date; the only open question is whether it has been
    // withdrawn, and that needs the server. One day, then the answer stops being assumed.
    NSTimeInterval last = [[NSUserDefaults standardUserDefaults] doubleForKey:kSCILastCheckDefault];
    if (last > 0 && [NSDate date].timeIntervalSince1970 - last > SCILicenseGraceSeconds) {
        return SCILicenseStateGrace;
    }

    return SCILicenseStateValid;
}

#pragma mark - The store build

///
/// **One code, any number of devices, and a date it stops on.**
///
/// Everything else in this file is device-bound and revocable. This is not, by request: a store
/// sells copies, not licences to named people, and asking a shop's customers for a device code
/// each is asking the shop to run a support desk.
///
/// What that costs, stated rather than glossed: **the code is inside a dylib the store hands out,
/// so anyone with the dylib can read it.** There is nothing to hide it behind — a credential that
/// works on any device with no server has nothing left to check against. The two things it does
/// buy are real, and they are what it is for:
///
///   * it works on **these builds only**. An ordinary Albrhi does not merely refuse this code; the
///     path that would accept it is not compiled in, so there is no string to find;
///   * and the build **stops by itself** on a date fixed when it was built. Three months, then the
///     store gets a fresh dylib. It is a shelf life rather than a lock, and it is the only part of
///     this that cannot be shared away.
///
static NSString *const kSCIStoreCodePref = @"albrhi_store_code";


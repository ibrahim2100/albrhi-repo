///
/// Activates a store copy against the server.
///
/// **The compiled-in date was the first version of this and the server replaced it for what it
/// could not do.** A date inside the dylib cannot be extended without rebuilding, cannot be
/// withdrawn at all, and tells the shop nothing about how many devices are using its copies --
/// which is the question a shop asks before renewing. So the code goes to the server, which
/// answers with an ordinary signed token: renewal, grace, revocation and the seven-day window all
/// work exactly as they do for a named licence, with no second mechanism to keep in step.
///
/// Unlimited devices is the *server's* rule, not an absence of one here. It counts them.
// Declared here because this function sits above them in the file: both belong to the server
// section further down, and moving that section up to satisfy one caller would put the network
// code in the middle of the offline verifier for no reason.
static BOOL SCIAcceptServerToken(NSString *token);
static SCILicenseServerResult SCIResultForState(NSString *state);
static void SCIPostJSON(NSString *path, NSDictionary *body,
                        void (^completion)(NSDictionary *_Nullable answer, NSInteger status));

void SCILicenseActivateStore(NSString *code, void (^completion)(SCILicenseServerResult result)) {
    NSString *store = SCILicenseStoreID();
    if (!store.length) { if (completion) completion(SCILicenseServerNoLicence); return; }
    if (!SCILicenseServerBase()) { if (completion) completion(SCILicenseServerNotConfigured); return; }

    NSMutableDictionary *body = [@{
        @"store": store,
        @"code": code ?: @"",
        @"dev": SCILicenseFingerprint(),
    } mutableCopy];

    NSString *product = SCIPanelProductForThisApp();
    if (product.length) {
        body[@"product"] = product;
        NSString *const *version = (NSString *const *)dlsym(RTLD_DEFAULT, "SCIVersionString");
        if (version && *version) body[@"version"] = *version;
    }

    SCIPostJSON(@"/v1/store", body, ^(NSDictionary *answer, NSInteger status) {
        if (status != 200 || !answer) {
            if (completion) completion(SCILicenseServerUnreachable);
            return;
        }

        NSString *token = answer[@"token"];
        if ([token isKindOfClass:[NSString class]] && SCIAcceptServerToken(token)) {
            // Remembered as well, so the screen can say "activated" before the first renewal and
            // so a reinstall of the app does not send somebody back to the shop for the code.
            [[NSUserDefaults standardUserDefaults] setObject:code forKey:kSCIStoreCodePref];
            if (completion) completion(SCILicenseServerOK);
            return;
        }

        if (completion) completion(SCIResultForState(answer[@"state"]));
    });
}

BOOL SCILicenseStoreAccepts(NSString *code) {
    NSString *wanted = SCILicenseStoreID();
    if (!wanted.length || !code.length) return NO;

    // Typed by a person, so folded the way every other code here is: spaces, dashes and case are
    // how somebody writes a word down, not part of it.
    NSString *given = [[code stringByTrimmingCharactersInSet:
                            [NSCharacterSet whitespaceAndNewlineCharacterSet]] lowercaseString];
    given = [given stringByReplacingOccurrencesOfString:@"-" withString:@""];

    // **Shape only.** Whether this code is live, and until when, is the server's answer -- see
    // SCILicenseActivateStore. This says one thing: that the string somebody typed is the code
    // this build was made for, so it can be sent to the right place rather than tried as a key.
    //
    // The compiled date stays as a backstop for a copy that can never reach the server at all;
    // where there is a server it decides, and it can extend, withdraw and count.
    return [given isEqualToString:wanted.lowercaseString];
}

BOOL SCILicenseStoreActive(void) {
    NSString *store = SCILicenseStoreID();
    if (!store.length) return NO;

    // The token the server issued, checked the way every other token is: signed, for this device,
    // in date. A store copy is licensed by the same machinery as everything else -- what differs
    // is only who the server hands one to.
    NSDictionary *payload = nil;
    if (SCIEvaluateKey(SCILicenseStoredKey(), &payload) == SCILicenseStateValid) {
        NSString *tier = payload[@"tier"];
        if ([tier isKindOfClass:[NSString class]] &&
            [tier isEqualToString:[@"store:" stringByAppendingString:store]]) {
            return YES;
        }
    }

    // The offline backstop: a copy built with a window and never able to reach a server. It is
    // deliberately the *second* answer -- where the server can be asked, its word is the one that
    // can be extended and withdrawn.
    NSString *stored = [[NSUserDefaults standardUserDefaults] stringForKey:kSCIStoreCodePref];
    if (!SCILicenseStoreAccepts(stored)) return NO;

    NSTimeInterval until = SCILicenseStoreExpiry();
    return until > 0 && [NSDate date].timeIntervalSince1970 < until;
}

/// Remembers the code on this device. Local defaults, not the panel's domain: a store build is
/// installed inside one app and has no panel to share anything with.
void SCILicenseStoreRemember(NSString *code) {
    if (!SCILicenseStoreAccepts(code)) return;
    [[NSUserDefaults standardUserDefaults] setObject:code forKey:kSCIStoreCodePref];
}

NSString *SCILicenseScope(void) {
    NSDictionary *payload = nil;
    if (SCIEvaluateKey(SCILicenseStoredKey(), &payload) == SCILicenseStateValid) {
        NSString *tier = payload[@"tier"];
        if ([tier isKindOfClass:[NSString class]] && tier.length) return tier;
        return @"suite";
    }

    // A redeemed code keeps its own tier beside it, written when the server answered. Same
    // question, different instrument.
    NSString *stored = SCIPanelReadString(kSCICodeTierPref, nil);
    if (stored.length) return stored;

    return @"suite";
}

BOOL SCILicenseCoversProduct(NSString *product) {
    if (!product.length) return YES;          // a caller that does not know what it is

    NSString *scope = SCILicenseScope();

    // The jailbreak licence covers everything, and so does anything unrecognised: a scope this
    // build has not been taught is a licence somebody paid for, and refusing it would be this
    // project deciding that its own newer server is wrong.
    if ([scope isEqualToString:@"suite"] || [scope isEqualToString:@"apps"]) return YES;

    // A store token covers everything in that store's own builds, and nothing anywhere else: an
    // ordinary build has no store id, so `store:` never matches and the licence is refused --
    // which is the exclusivity, expressed where it can be checked rather than promised.
    if ([scope hasPrefix:@"store:"]) {
        NSString *store = SCILicenseStoreID();
        return store.length && [[scope substringFromIndex:6] isEqualToString:store];
    }

    if ([scope hasPrefix:@"app:"]) return [[scope substringFromIndex:4] isEqualToString:product];

    return YES;
}

BOOL SCILicenseAllowsProduct(NSString *product) {
    if (!SCILicenseIsEnforced()) return YES;

    // The store code first, and it answers alone: a store build has no server, no device binding
    // and no scope to check -- one code for every app in that store's own dylibs.
    if (SCILicenseStoreActive()) return YES;

    if (!SCILicenseAllows()) return NO;
    return SCILicenseCoversProduct(product);
}

BOOL SCILicenseAllows(void) {
    if (!SCILicenseIsEnforced()) return YES;

    switch (SCILicenseCurrentState()) {
        case SCILicenseStateValid:
            return YES;

        // Grace is *allowed*, and that is the point of having it: the key is genuine and in
        // date, and the only thing missing is a network this code has no right to demand. It is
        // reported, not punished.
        case SCILicenseStateGrace:
            return YES;

        default:
            return NO;
    }
}

BOOL SCILicenseStoreKey(NSString *key, SCILicenseState *outState) {
    NSDictionary *payload = nil;
    SCILicenseState state = SCIEvaluateKey(key, &payload);
    if (outState) *outState = state;

    if (state != SCILicenseStateValid) return NO;

    CFPreferencesSetAppValue((__bridge CFStringRef)kSCILicenseKeyPref,
                             (__bridge CFStringRef)key,
                             (__bridge CFStringRef)@"com.albrhi.panel");
    CFPreferencesAppSynchronize((__bridge CFStringRef)@"com.albrhi.panel");

    // A key accepted now is a key confirmed now: without this the very first launch after
    // entering one would already be a day into its grace period.
    [[NSUserDefaults standardUserDefaults] setDouble:[NSDate date].timeIntervalSince1970
                                              forKey:kSCILastCheckDefault];
    return YES;
}

void SCILicenseForgetKey(void) {
    CFPreferencesSetAppValue((__bridge CFStringRef)kSCILicenseKeyPref, NULL,
                             (__bridge CFStringRef)@"com.albrhi.panel");
    CFPreferencesAppSynchronize((__bridge CFStringRef)@"com.albrhi.panel");
}


#pragma mark - Check-in

///
/// **How often this device should ask, and it is not one number.**
///
/// Six hours flat was the old answer, and it was expensive in a way nothing on the device could
/// see: the last-check time lives in `[NSUserDefaults standardUserDefaults]` — *each app's own*
/// domain — while the token it renews lives in the shared one. So a phone with four patched apps
/// asked **sixteen times a day** and renewed the same token sixteen times, and every one of those
/// is a write on the server's side. Cloudflare KV's free allowance is a thousand writes a day:
/// sixty phones, and ordinary customers exhaust it between them, after which activation and
/// renewal fail for everybody until midnight. **The ceiling was never an attacker.**
///
/// What the cadence has to guarantee is smaller than it looks. The token lasts seven days, so one
/// ask a day leaves six days of slack — and the only thing that genuinely wants speed is the day
/// the *term* ends, because that is when a customer who has just paid is waiting for the tweak to
/// come back. So the interval is driven by the licence's own end date rather than by the token's,
/// and the two rules are combined by taking whichever is shorter.
///
/// The cost is stated rather than hidden: a withdrawn licence now dies within a day instead of
/// within six hours. The design already promises only "within a week", and this sits well inside
/// it.
///
/// The table on its own, as a function of two numbers — so it can be tested without a device, a
/// server or a stored key, which is the only reason it is written apart from the code that
/// gathers them.
///
/// `tokenLeft` is seconds until the signed token expires, negative when there is no valid one.
/// `termLeft` is seconds until the licence itself ends; **`kSCITermForever` means it never does**.
NSTimeInterval SCICheckIntervalFor(double tokenLeft, double termLeft) {
    // **The last-chance rule, unchanged.** A token with under two days left belongs to a phone
    // that has been unreachable for five days, and the next minute of signal is the only thing
    // between a paying user and a closed gate. Nothing below may make this slower.
    if (tokenLeft >= 0 && tokenLeft < 2 * 86400) return 30 * 60;

    // Lifetime, or nothing stored yet. There is no end approaching, so the only question left is
    // whether the licence has been withdrawn — and that has a week to arrive in.
    if (termLeft == kSCITermForever) return 24 * 60 * 60;

    // Ended already, and waiting for the renewal that turns it back on. Eight hours is eager
    // without being a device knocking on a door all day; after a week with no answer nobody is
    // coming, and it settles to daily.
    if (termLeft <= 0) return termLeft > -7 * 86400 ? 8 * 60 * 60 : 24 * 60 * 60;

    // The last three days, where a payment is most likely to be in flight.
    if (termLeft < 3 * 86400) return 8 * 60 * 60;

    return 24 * 60 * 60;
}

static NSTimeInterval SCICheckInterval(void) {
    double now = [NSDate date].timeIntervalSince1970;

    double tokenLeft = -1;
    NSDictionary *payload = nil;
    if (SCIEvaluateKey(SCILicenseStoredKey(), &payload) == SCILicenseStateValid) {
        NSNumber *expiry = payload[@"exp"];
        if ([expiry isKindOfClass:[NSNumber class]]) tokenLeft = expiry.doubleValue - now;
    }

    double until = SCILicenseTermEnds();
    return SCICheckIntervalFor(tokenLeft, until <= 0 ? kSCITermForever : until - now);
}

void SCILicenseCheckInIfDue(void) {
    NSUserDefaults *defaults = [NSUserDefaults standardUserDefaults];
    NSTimeInterval last = [defaults doubleForKey:kSCILastCheckDefault];

    //
    // **With a server configured, the check-in is a renewal and it runs whether or not there is a
    // key already.** A device that has just been approved has nothing stored, so a `return` on an
    // empty key would mean the licence never arrives without somebody opening the panel — which
    // is exactly the sort of "works if you know the trick" behaviour this project keeps ending up
    // with when a gate is placed before the thing it gates.
    //
    if (SCILicenseServerBase()) {
        if (last > 0 && [NSDate date].timeIntervalSince1970 - last < SCICheckInterval()) return;

        // Not waited on, and its result is deliberately dropped: whatever it decides lands in the
        // stored token for the *next* question, and a launch must never sit behind a network call.
        SCILicenseSyncWithServer(nil);
        return;
    }

    if (!SCILicenseStoredKey()) return;
    if (last > 0 && [NSDate date].timeIntervalSince1970 - last < kSCILicenseCheckInterval) return;

    NSURL *url = [NSURL URLWithString:kSCILicenseEndpoint];
    if (!url) return;

    NSURLSessionConfiguration *configuration =
        [NSURLSessionConfiguration ephemeralSessionConfiguration];

    // Short, and never waited on. A licence check that can hold up a launch is a licence check
    // that will one day hold up every launch, and this project has a standing rule against a
    // fallback that hides a fault -- a hung request is that fault with a spinner over it.
    configuration.timeoutIntervalForRequest = 8;
    configuration.timeoutIntervalForResource = 12;

    NSURLSession *session = [NSURLSession sessionWithConfiguration:configuration];
    NSURLSessionDataTask *task = [session dataTaskWithURL:url
        completionHandler:^(NSData *data, NSURLResponse *response, NSError *error) {
            NSInteger status = [response isKindOfClass:[NSHTTPURLResponse class]]
                ? ((NSHTTPURLResponse *)response).statusCode : 0;

            // Only a real answer counts. A timeout, a captive portal's login page or a 500 must
            // never be read as "revoked" -- that would take a paying user's features away
            // because a coffee shop's wifi asked them to sign in.
            if (error || status != 200 || !data.length) return;

            id parsed = [NSJSONSerialization JSONObjectWithData:data options:0 error:NULL];
            NSArray *ids = [parsed isKindOfClass:[NSDictionary class]] ? parsed[@"revoked"] : nil;

            if ([ids isKindOfClass:[NSArray class]]) {
                [defaults setObject:ids forKey:kSCIRevokedDefault];
            }
            [defaults setDouble:[NSDate date].timeIntervalSince1970 forKey:kSCILastCheckDefault];
        }];

    [task resume];
}


#pragma mark - The server

///
/// Albrhi's own licence server, compiled in.
///
/// **Without this every buyer would have to be told a URL and type it correctly before they could
/// even ask for a licence**, which is not a purchase flow, it is a support thread. The preference
/// below still overrides it -- for testing, for a staging deployment, and for anybody who would
/// rather run their own -- but the default is the thing that makes "open Settings and tap Request"
/// work on a phone that has never been configured.
///
/// https, and the check below enforces it rather than trusting this constant: a licence arriving
/// over plain http could be swapped in flight by anyone on the same wifi.
static NSString *const kSCIDefaultServer = @"https://albrhi-licence.ibrahimalrahan01.workers.dev";

NSString *SCILicenseServerBase(void) {
    //
    // **Compiled in, and not overridable at runtime — for the same reason the enforcement switch
    // is gone.**
    //
    // A settable address is a way around the gate, not a convenience: point it at a server you
    // control and it issues you a licence signed by *your* key... except it cannot, because the
    // token is verified against the public key compiled into this binary. So the worst a swapped
    // address achieves is no licence at all. It comes out anyway, because a control that cannot
    // help a user and can only confuse one is not worth the row it occupies — and because the
    // next person to read this file should not have to work out which of those two it was.
    //
    // A staging deployment sets SCI_LICENCE_SERVER at build time. That is a decision made by
    // whoever builds the package, which is the right place for it.
    //
#ifdef SCI_LICENCE_SERVER
    NSString *base = @SCI_LICENCE_SERVER;
#else
    NSString *base = @"https://albrhi-licence.ibrahimalrahan01.workers.dev";
#endif

    // Trailing slashes trimmed here rather than at four call sites, and https demanded rather
    // than assumed: a licence arriving over plain http could be swapped in flight by anyone on
    // the same wifi, and the signature would still check out because they could simply replay an
    // older, longer-lived one.
    while ([base hasSuffix:@"/"]) base = [base substringToIndex:base.length - 1];
    if (![base hasPrefix:@"https://"]) return nil;

    return base;
}


/// One JSON POST, with every failure folded into "nothing was decided".
///
/// **A network problem is never reported as a licence problem.** That distinction is the single
/// most important thing in this file: a timeout, a 500 or a captive portal's login page must not
/// cost a paying user their features, and the seven-day token is what makes it safe to simply
/// shrug and try again later.
static void SCIPostJSON(NSString *path, NSDictionary *body,
                        void (^completion)(NSDictionary *_Nullable answer, NSInteger status)) {
    NSString *base = SCILicenseServerBase();
    if (!base) { completion(nil, 0); return; }

    NSURL *url = [NSURL URLWithString:[base stringByAppendingString:path]];
    if (!url) { completion(nil, 0); return; }

    NSMutableURLRequest *request = [NSMutableURLRequest requestWithURL:url];
    request.HTTPMethod = @"POST";
    [request setValue:@"application/json" forHTTPHeaderField:@"Content-Type"];
    request.HTTPBody = [NSJSONSerialization dataWithJSONObject:body options:0 error:NULL];
    request.timeoutInterval = 12;

    NSURLSessionConfiguration *configuration =
        [NSURLSessionConfiguration ephemeralSessionConfiguration];
    configuration.timeoutIntervalForRequest = 12;
    configuration.timeoutIntervalForResource = 20;

    NSURLSession *session = [NSURLSession sessionWithConfiguration:configuration];
    [[session dataTaskWithRequest:request
                completionHandler:^(NSData *data, NSURLResponse *response, NSError *error) {
        NSInteger status = [response isKindOfClass:[NSHTTPURLResponse class]]
            ? ((NSHTTPURLResponse *)response).statusCode : 0;

        id parsed = data.length ? [NSJSONSerialization JSONObjectWithData:data options:0 error:NULL]
                                : nil;

        dispatch_async(dispatch_get_main_queue(), ^{
            completion([parsed isKindOfClass:[NSDictionary class]] ? parsed : nil,
                       error ? 0 : status);
        });
    }] resume];
}

/// Stores a token the server signed, but only after checking it here.
///
/// The server is trusted to *decide*; it is not trusted to be reachable, correct, or even the
/// right server. A token that does not verify against the compiled public key, or is not for this
/// device, is dropped -- so pointing the address at something hostile gains nothing but a
/// refusal.
static BOOL SCIAcceptServerToken(NSString *token) {
    NSDictionary *payload = nil;
    if (SCIEvaluateKey(token, &payload) != SCILicenseStateValid) return NO;

    CFStringRef domain = (__bridge CFStringRef)@"com.albrhi.panel";
    CFPreferencesSetAppValue((__bridge CFStringRef)kSCILicenseKeyPref,
                             (__bridge CFStringRef)token, domain);
    CFPreferencesAppSynchronize(domain);

    [[NSUserDefaults standardUserDefaults] setDouble:[NSDate date].timeIntervalSince1970
                                              forKey:kSCILastCheckDefault];
    return YES;
}

static SCILicenseServerResult SCIResultForState(NSString *state) {
    if ([state isEqualToString:@"revoked"]) return SCILicenseServerRevoked;
    if ([state isEqualToString:@"expired"]) return SCILicenseServerExpired;
    return SCILicenseServerNoLicence;
}

void SCILicenseSyncWithServer(void (^completion)(SCILicenseServerResult)) {
    void (^finish)(SCILicenseServerResult) = ^(SCILicenseServerResult result) {
        if (completion) completion(result);
    };

    if (!SCILicenseServerBase()) { finish(SCILicenseServerNotConfigured); return; }

    //
    // **The check-in says which tweak is asking, and at what version.**
    //
    // It already carried the device id; these three fields are what turn a licence's own page in
    // the panel from a row into an answer -- *which* apps a key is running in, and whether the
    // one complaining is even on the current build. Nothing about the person is sent: the product
    // name is one of four words this project chose, the version is ours, and the bundle
    // identifier is the app the tweak was written for and could not be anything else.
    //
    NSMutableDictionary *hello = [@{@"dev": SCILicenseFingerprint()} mutableCopy];

    NSString *product = SCIPanelProductForThisApp();
    if (product.length) {
        hello[@"product"] = product;
        hello[@"app"] = [[NSBundle mainBundle] bundleIdentifier] ?: @"";

        // The tweak's own version, declared by every tweak here as SCIVersionString. Weakly
        // looked up rather than imported: the panel links this file too and has no such symbol.
        NSString *const *version = (NSString *const *)dlsym(RTLD_DEFAULT, "SCIVersionString");
        if (version && *version) hello[@"version"] = *version;
    }

    SCIPostJSON(@"/v1/hello", hello,
                ^(NSDictionary *answer, NSInteger status) {
        if (status != 200 || !answer) { finish(SCILicenseServerUnreachable); return; }

        NSString *token = answer[@"token"];
        if ([token isKindOfClass:[NSString class]] && SCIAcceptServerToken(token)) {
            finish(SCILicenseServerOK);
            return;
        }

        // A pending request is its own answer, not "no licence": the panel says "asked, waiting"
        // rather than offering to ask again, which is what stops one person filling the inbox.
        if ([answer[@"pending"] boolValue]) { finish(SCILicenseServerPending); return; }

        SCILicenseServerResult result = SCIResultForState(answer[@"state"]);

        //
        // **A definite answer is acted on; only an absent one is ignored.**
        //
        // The token on the device stays valid by signature for a week, so without this a
        // withdrawn licence went on working until that week ran out -- reported as exactly
        // that: "I revoked it and it still works".
        //
        // The distinction that makes this safe is the one this whole file is built around: a
        // 200 carrying `revoked` is the server *deciding*, and a timeout or a captive portal is
        // the server saying nothing. Only the first reaches here -- `status != 200` returned
        // above -- so a coffee shop's wifi can still never take a paying user's licence away.
        //
        if (result == SCILicenseServerRevoked || result == SCILicenseServerNoLicence ||
            result == SCILicenseServerExpired) {
            SCILicenseForgetKey();
        }

        finish(result);
    });
}

void SCILicenseStartTrial(void (^completion)(SCILicenseServerResult)) {
    if (!SCILicenseServerBase()) { completion(SCILicenseServerNotConfigured); return; }

    SCIPostJSON(@"/v1/trial", @{@"dev": SCILicenseFingerprint()},
                ^(NSDictionary *answer, NSInteger status) {
        if (status == 0 || !answer) { completion(SCILicenseServerUnreachable); return; }

        NSString *token = answer[@"token"];
        if (status == 200 && [token isKindOfClass:[NSString class]] && SCIAcceptServerToken(token)) {
            completion(SCILicenseServerOK);
            return;
        }

        // Three refusals, three answers. "you already used it", "you already have a licence" and
        // "the network did not answer" need three different things said to a person, and folding
        // them into one failure is how somebody who already paid is told to buy again.
        NSString *state = answer[@"state"];
        if ([state isEqualToString:@"trial_used"])       { completion(SCILicenseServerTrialUsed); return; }
        if ([state isEqualToString:@"already_licensed"]) { completion(SCILicenseServerAlreadyLicensed); return; }

        completion(SCILicenseServerUnreachable);
    });
}

BOOL SCILicenseIsLifetime(void) {
    NSDictionary *payload = nil;
    if (SCIEvaluateKey(SCILicenseStoredKey(), &payload) != SCILicenseStateValid) return NO;

    // `until` absent or zero on a *valid* licence means no end date. The validity check above is
    // what makes that safe to read: without it, "no licence at all" would answer the same way.
    NSNumber *until = payload[@"until"];
    if (![until isKindOfClass:[NSNumber class]]) return NO;
    return until.doubleValue == 0;
}

void SCILicenseRequestFromServer(NSInteger days, BOOL lifetime,
                                 NSString *name, NSString *contact, NSString *note,
                                 void (^completion)(SCILicenseServerResult)) {
    if (!SCILicenseServerBase()) { completion(SCILicenseServerNotConfigured); return; }

    NSMutableDictionary *body = [@{
        @"dev": SCILicenseFingerprint(),
        @"days": @(days < 1 ? 365 : days),
        @"lifetime": @(lifetime),
    } mutableCopy];

    NSCharacterSet *blank = [NSCharacterSet whitespaceAndNewlineCharacterSet];
    for (NSArray *pair in @[@[@"name", name ?: @""], @[@"contact", contact ?: @""],
                            @[@"note", note ?: @""]]) {
        NSString *value = [pair[1] stringByTrimmingCharactersInSet:blank];
        if (value.length) body[pair[0]] = value;
    }

    SCIPostJSON(@"/v1/request", body, ^(NSDictionary *answer, NSInteger status) {
        completion(status == 200 && answer ? SCILicenseServerPending
                                          : SCILicenseServerUnreachable);
    });
}

void SCILicenseRedeemWithServer(NSString *code, void (^completion)(SCILicenseRedeemResult)) {
    if (!SCILicenseServerBase()) {
        // Falls back to the published list, which is the scheme that shipped before the server
        // existed. A device pointed at no server can still redeem.
        SCILicenseRedeemCode(code, completion);
        return;
    }

    SCIPostJSON(@"/v1/redeem", @{@"dev": SCILicenseFingerprint(), @"code": code ?: @""},
                ^(NSDictionary *answer, NSInteger status) {
        if (status == 0 || !answer) { completion(SCILicenseRedeemOffline); return; }

        NSString *token = answer[@"token"];
        if (status == 200 && [token isKindOfClass:[NSString class]] &&
            SCIAcceptServerToken(token)) {
            completion(SCILicenseRedeemedOK);
            return;
        }

        NSString *state = answer[@"state"];
        if ([state isEqualToString:@"malformed"])     { completion(SCILicenseRedeemMalformed); return; }
        if ([state isEqualToString:@"window_closed"]) { completion(SCILicenseRedeemWindowClosed); return; }

        // "Already bound to another device" is its own sentence in the panel: it is the one
        // refusal here that means the code was real and somebody else got there first.
        if ([state isEqualToString:@"already_used"])  { completion(SCILicenseRedeemTaken); return; }

        completion(SCILicenseRedeemUnknown);
    });
}

NSTimeInterval SCILicenseTermEnds(void) {
    NSDictionary *payload = nil;
    if (SCIEvaluateKey(SCILicenseStoredKey(), &payload) != SCILicenseStateValid) return 0;

    // `until` when the server set one, `exp` otherwise. A manually issued offline key has no
    // renewal cycle, so its expiry *is* its term -- and showing a seven-day renewal date to
    // somebody who bought a year is the kind of screen that generates a support message.
    NSNumber *until = payload[@"until"];
    if ([until isKindOfClass:[NSNumber class]]) {
        // Present and zero is a lifetime licence, which has no date to show -- and must not fall
        // through to `exp`, or the screen would announce that a lifetime licence ends next week.
        return until.doubleValue;
    }

    NSNumber *expiry = payload[@"exp"];
    return [expiry isKindOfClass:[NSNumber class]] ? expiry.doubleValue : 0;
}



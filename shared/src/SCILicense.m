const NSTimeInterval SCILicenseGraceSeconds = 24 * 60 * 60;   // one day, the owner's choice

/// How often the revocation call is allowed to run. Six hours: often enough that a revoked key
/// stops working the same day, rare enough that it is not a request per launch.
